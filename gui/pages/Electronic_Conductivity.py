                    st.dataframe(
                        pd.DataFrame(
                            conditional_sigma,
                            index=["x", "y", "z"],
                            columns=["x", "y", "z"],
                        ),
                        use_container_width=True,
                    )
                    st.caption(
                        "This absolute conductivity uses the explicitly assumed relaxation time; "
                        "the relaxation time is not calculated by this workflow."
                    )

