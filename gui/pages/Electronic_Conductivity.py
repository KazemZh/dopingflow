                        st.caption("Stored for reproducibility in S m⁻¹ s⁻¹.")
                        st.dataframe(
                            pd.DataFrame(
                                raw_sigma_tau,
                                index=["x", "y", "z"],
                                columns=["x", "y", "z"],
                            ),
                            use_container_width=True,
                        )

