def _parse_json_mapping(text: str, label: str) -> dict:
    text = text.strip()
    if not text:
        return {}
    try:
        value = json.loads(text)
    except json.JSONDecodeError as exc:
        st.error(f"{label} must be valid JSON: {exc}")
        return {}
    if not isinstance(value, dict):
        st.error(f"{label} must be a JSON object.")
        return {}
    return value


def _inherited_dft_settings() -> dict:
    inherited = dict(oxidation.get("dft_electronic", {}) or {})
    methods = oxidation.get("methods", [])
    if isinstance(methods, str):
        methods = [item.strip() for item in methods.split(",") if item.strip()]
    if "dft-auto" in methods or (
        str(oxidation.get("strategy", "")).lower() == "dft" and not methods
    ):
        inherited.update(dict(oxidation.get("dft_auto", {}) or {}))
    return inherited


def _readable_transport_row(row: dict) -> dict:
    """Backfill the human-readable unit for results generated by older revisions."""
    row = dict(row)
    if (
        "sigma_over_tau_trace_average_S_per_cm_per_fs" not in row
        and row.get("sigma_over_tau_trace_average_S_per_m_per_s") is not None
    ):
        row["sigma_over_tau_trace_average_S_per_cm_per_fs"] = (
            float(row["sigma_over_tau_trace_average_S_per_m_per_s"]) * 1.0e-17
        )
    if (
        "sigma_over_tau_S_per_cm_per_fs" not in row
        and row.get("sigma_over_tau_S_per_m_per_s") is not None
    ):
        row["sigma_over_tau_S_per_cm_per_fs"] = (
            pd.DataFrame(row["sigma_over_tau_S_per_m_per_s"]) * 1.0e-17
        ).values.tolist()
    return row


